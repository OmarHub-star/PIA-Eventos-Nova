from datetime import datetime, timezone
from typing import Protocol


class Clock(Protocol):
    def now(self) -> datetime: ...


class SystemClock:
    def now(self):
        return datetime.now(timezone.utc)


class UnitOfWork(Protocol):
    def get(self, kind: str, entity_id: str) -> dict: ...
    def list(self, kind: str) -> list[dict]: ...
    def save(self, kind: str, entity_id: str, data: dict): ...
    def emit(self, name: str, event_id: str, actor: str, at: str, payload: dict): ...
    def book(self, supplier_id: str, day: str, request_id: str): ...
    def release(self, request_id: str): ...
    def commit(self): ...
